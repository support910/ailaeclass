CREATE TABLE IF NOT EXISTS public.payment_orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  reference text NOT NULL UNIQUE CHECK (reference ~ '^FPS-[0-9]{6}-[A-F0-9]{10}$'),
  payer_profile_id uuid NOT NULL REFERENCES public.profile(id) ON DELETE RESTRICT,
  payer_email text NOT NULL,
  organization_id uuid REFERENCES public.organization(id) ON DELETE SET NULL,
  amount_minor bigint NOT NULL CHECK (amount_minor BETWEEN 1 AND 100000000),
  currency text NOT NULL DEFAULT 'HKD' CHECK (currency = 'HKD'),
  payment_method text NOT NULL DEFAULT 'fps' CHECK (payment_method = 'fps'),
  status text NOT NULL DEFAULT 'awaiting_payment'
    CHECK (status IN ('awaiting_payment', 'receipt_submitted', 'verified', 'rejected', 'cancelled', 'expired')),
  receipt_path text,
  receipt_content_type text,
  receipt_original_name text,
  submitted_at timestamptz,
  reviewed_at timestamptz,
  reviewed_by uuid REFERENCES public.profile(id) ON DELETE SET NULL,
  review_note text NOT NULL DEFAULT '',
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS payment_orders_payer_created_idx
  ON public.payment_orders (payer_profile_id, created_at DESC);
CREATE INDEX IF NOT EXISTS payment_orders_status_created_idx
  ON public.payment_orders (status, created_at DESC);

CREATE TABLE IF NOT EXISTS public.payment_audit_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES public.payment_orders(id) ON DELETE RESTRICT,
  actor_profile_id uuid REFERENCES public.profile(id) ON DELETE SET NULL,
  action text NOT NULL,
  from_status text,
  to_status text NOT NULL,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS payment_audit_logs_order_created_idx
  ON public.payment_audit_logs (order_id, created_at ASC);

ALTER TABLE public.payment_orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.payment_audit_logs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.payment_orders FROM anon, authenticated;
REVOKE ALL ON public.payment_audit_logs FROM anon, authenticated;
GRANT ALL ON public.payment_orders TO service_role;
GRANT SELECT ON public.payment_audit_logs TO service_role;
